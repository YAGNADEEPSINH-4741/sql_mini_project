-- 1. Foreign Key Performance Indexes (prevents table locks on parent updates)
CREATE INDEX IDX_ACC_CUSTOMER_ID ON BANK_ACCOUNTS(CUSTOMER_ID);
CREATE INDEX IDX_ACC_BRANCH_ID ON BANK_ACCOUNTS(BRANCH_ID);
CREATE INDEX IDX_ACC_TYPE_ID ON BANK_ACCOUNTS(TYPE_ID);

CREATE INDEX IDX_TXN_ACCOUNT_ID ON TRANSACTIONS(ACCOUNT_ID);
CREATE INDEX IDX_TXN_RELATED_ACC ON TRANSACTIONS(RELATED_ACCOUNT_ID);

CREATE INDEX IDX_BENEF_CUSTOMER_ID ON BENEFICIARIES(CUSTOMER_ID);

CREATE INDEX IDX_LOAN_CUSTOMER_ID ON LOANS(CUSTOMER_ID);
CREATE INDEX IDX_LOAN_BRANCH_ID ON LOANS(BRANCH_ID);

CREATE INDEX IDX_PAYMENT_LOAN_ID ON LOAN_PAYMENTS(LOAN_ID);

CREATE INDEX IDX_EMP_BRANCH_ID ON EMPLOYEES(BRANCH_ID);

-- 2. Query Search & Filter Indexes
CREATE INDEX IDX_CUST_NAME ON CUSTOMERS(LAST_NAME, FIRST_NAME);
CREATE INDEX IDX_CUST_CITY ON CUSTOMERS(CITY);
CREATE INDEX IDX_CUST_KYC ON CUSTOMERS(KYC_STATUS);

CREATE INDEX IDX_ACC_STATUS ON BANK_ACCOUNTS(ACCOUNT_STATUS);
CREATE INDEX IDX_ACC_BALANCE ON BANK_ACCOUNTS(BALANCE);

CREATE INDEX IDX_TXN_DATE ON TRANSACTIONS(TRANSACTION_DATE);
CREATE INDEX IDX_TXN_TYPE ON TRANSACTIONS(TRANSACTION_TYPE);
CREATE INDEX IDX_TXN_STATUS ON TRANSACTIONS(TRANSACTION_STATUS);

CREATE INDEX IDX_LOAN_STATUS ON LOANS(LOAN_STATUS);
CREATE INDEX IDX_LOAN_TYPE ON LOANS(LOAN_TYPE);

CREATE INDEX IDX_AUDIT_TABLE_OP ON AUDIT_LOGS(TABLE_NAME, OPERATION_TYPE);
CREATE INDEX IDX_AUDIT_TIMESTAMP ON AUDIT_LOGS(CHANGED_AT);

