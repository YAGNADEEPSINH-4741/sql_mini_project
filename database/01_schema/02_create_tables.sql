    CREATED_AT      DATE            DEFAULT SYSDATE NOT NULL
);

-- 4. ACCOUNT_TYPES
CREATE TABLE ACCOUNT_TYPES (
    TYPE_ID             NUMBER(5)       NOT NULL,
    TYPE_NAME           VARCHAR2(50)    NOT NULL,
    MIN_BALANCE         NUMBER(12,2)    DEFAULT 1000.00 NOT NULL,
